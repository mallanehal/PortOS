// Load one simulation by rebuilding the frontend configuration from normalized tables.
app.get("/api/simulations/:id", async (req, res) => {
    const simulationId = Number(req.params.id);
    if (!Number.isSafeInteger(simulationId) || simulationId < 1) {
        return res.status(400).json({ error: "Invalid simulation ID" });
    }

    try {
        const [simulations] = await promiseDb.execute(
            "SELECT simulation_id AS id, name, created_at FROM simulations WHERE simulation_id = ?",
            [simulationId]
        );
        if (!simulations.length) {
            return res.status(404).json({ error: "Saved simulation not found" });
        }

        // Resources are stored in one table with a resource_type discriminator.
        const [resourceRows] = await promiseDb.execute(
            "SELECT resource_type, resource_number, size FROM resources WHERE simulation_id = ? ORDER BY resource_type, resource_number",
            [simulationId]
        );
        // JOIN requests to their ships so each request can be returned with its source ship ID.
        const [shipRequestRows] = await promiseDb.execute(`
            SELECT sh.source_ship_id, sh.name, sh.type, sh.country, sh.captain_name,
                sr.pid, request_ship.source_ship_id AS request_ship_id,
                sr.priority, sr.arrival, sr.burst, sr.berth_count, sr.crane_count, sr.truck_count
            FROM ships sh
            LEFT JOIN ship_requests sr
                ON sr.simulation_id = sh.simulation_id AND sr.ship_id = sh.ship_id
            LEFT JOIN ships request_ship
                ON request_ship.simulation_id = sr.simulation_id AND request_ship.ship_id = sr.ship_id
            WHERE sh.simulation_id = ?
            ORDER BY sh.source_ship_id, sr.pid
        `, [simulationId]);

        // Convert database rows back into the arrays expected by the simulator UI.
        const configuration = { berths: [], cranes: [], trucks: [], ships: [], processes: [] };
        const resourceKeys = { berth: "berths", crane: "cranes", truck: "trucks" };
        for (const resource of resourceRows) {
            configuration[resourceKeys[resource.resource_type]].push({
                num: resource.resource_number,
                size: resource.size,
            });
        }

        const shipsById = new Map();
        for (const row of shipRequestRows) {
            if (!shipsById.has(row.source_ship_id)) {
                const ship = {
                    ship_id: row.source_ship_id,
                    name: row.name,
                    type: row.type,
                    country: row.country,
                    captain_name: row.captain_name,
                };
                shipsById.set(row.source_ship_id, ship);
                configuration.ships.push(ship);
            }
            if (row.pid !== null) {
                configuration.processes.push({
                    pid: row.pid,
                    ship_id: row.request_ship_id,
                    priority: row.priority,
                    arrival: row.arrival,
                    burst: row.burst,
                    berths: row.berth_count,
                    cranes: row.crane_count,
                    trucks: row.truck_count,
                });
            }
        }
        configuration.processes.sort((left, right) => left.pid - right.pid);

        res.json({ ...simulations[0], configuration });
    } catch (error) {
        console.error("Could not fetch saved simulation:", error.message);
        res.status(500).json({ error: "Could not fetch saved simulation" });
    }
});

// Reject malformed or out-of-range data before inserting relational records.
function validateSavedConfiguration(configuration) {
    const keys = ["berths", "cranes", "trucks", "ships", "processes"];
    if (!configuration || typeof configuration !== "object" || Array.isArray(configuration)
        || !keys.every((key) => Array.isArray(configuration[key]))) {
        return "Simulation configuration must include berths, cranes, trucks, ships, and processes arrays";
    }
    if (keys.some((key) => configuration[key].length === 0)) {
        return "A simulation needs at least one berth, crane, truck, ship, and process";
    }

    const resourceIds = new Map();
    for (const [key, type] of [["berths", "berth"], ["cranes", "crane"], ["trucks", "truck"]]) {
        const ids = new Set();
        for (const item of configuration[key]) {
            if (!item || !isDatabaseInteger(item.num, 1)
                || !["Small", "Medium", "Large"].includes(item.size)) {
                return `Every ${type} needs a positive ID and a valid size`;
            }
            if (ids.has(item.num)) return `${type} IDs must be unique`;
            ids.add(item.num);
        }
        resourceIds.set(type, ids);
    }

    const shipIds = new Set();
    for (const ship of configuration.ships) {
        if (!ship || !isDatabaseInteger(ship.ship_id, 1)
            || typeof ship.name !== "string" || !ship.name.trim()
            || typeof ship.type !== "string" || !ship.type.trim()
            || ship.name.length > 255 || ship.type.length > 100
            || (ship.country ?? "").length > 100 || (ship.captain_name ?? "").length > 255
            || !["country", "captain_name"].every((key) => typeof (ship[key] ?? "") === "string")
            || ["name", "type", "country", "captain_name"].some((key) => /[|\r\n]/.test(ship[key] ?? ""))) {
            return "Each ship needs a valid ID, name, type, country, and captain name";
        }
        if (shipIds.has(ship.ship_id)) return "Ship IDs must be unique";
        shipIds.add(ship.ship_id);
    }

    const processIds = new Set();
    for (const process of configuration.processes) {
        if (!process || !isDatabaseInteger(process.pid, 1)
            || !isDatabaseInteger(process.ship_id, 1) || !shipIds.has(process.ship_id)) {
            return "Each request needs a unique positive PID and a registered ship";
        }
        if (processIds.has(process.pid)) return "Request PIDs must be unique";
        processIds.add(process.pid);
        for (const key of ["priority", "arrival", "burst", "berths", "cranes", "trucks"]) {
            if (!isDatabaseInteger(process[key], key === "priority" || key === "burst" ? 1 : 0)) {
                return `P${process.pid} has an invalid ${key} value`;
            }
        }
        if (process.berths > resourceIds.get("berth").size
            || process.cranes > resourceIds.get("crane").size
            || process.trucks > resourceIds.get("truck").size) {
            return `P${process.pid} requests more resources than the port owns`;
        }
        if (process.berths + process.cranes + process.trucks === 0) {
            return `P${process.pid} must request at least one resource`;
        }
    }
    return null;
}

// MySQL INT UNSIGNED columns accept values from 0 through 4,294,967,295.
function isDatabaseInteger(value, minimum) {
    return Number.isSafeInteger(value) && value >= minimum && value <= 4294967295;
}

// Save the parent simulation and all its related rows atomically.
app.post("/api/simulations", async (req, res) => {
    const name = typeof req.body?.name === "string" ? req.body.name.trim() : "";
    const configuration = req.body?.configuration;
    if (!name || name.length > 120) {
        return res.status(400).json({ error: "Simulation name is required and must be 120 characters or fewer" });
    }
    const validationError = validateSavedConfiguration(configuration);
    if (validationError) return res.status(400).json({ error: validationError });

    let connection;
    let transactionStarted = false;
    try {
        connection = await promiseDb.getConnection();
        await connection.beginTransaction();
        transactionStarted = true;

        const [simulationResult] = await connection.execute(
            "INSERT INTO simulations (name) VALUES (?)",
            [name]
        );
        const simulationId = simulationResult.insertId;

        const resourceRows = [
            ...configuration.berths.map((resource) => [simulationId, "berth", resource.num, resource.size]),
            ...configuration.cranes.map((resource) => [simulationId, "crane", resource.num, resource.size]),
            ...configuration.trucks.map((resource) => [simulationId, "truck", resource.num, resource.size]),
        ];
        await connection.query(
            `INSERT INTO resources (simulation_id, resource_type, resource_number, size)
             VALUES ${resourceRows.map(() => "(?, ?, ?, ?)").join(", ")}`,
            resourceRows.flat()
        );

        const databaseShipIds = new Map();
        for (const ship of configuration.ships) {
            const [shipResult] = await connection.execute(
                `INSERT INTO ships (simulation_id, source_ship_id, name, type, country, captain_name)
                 VALUES (?, ?, ?, ?, ?, ?)`,
                [simulationId, ship.ship_id, ship.name.trim(), ship.type.trim(), (ship.country ?? "").trim(), (ship.captain_name ?? "").trim()]
            );
            databaseShipIds.set(ship.ship_id, shipResult.insertId);
        }

        const requestRows = configuration.processes.map((process) => [
            simulationId,
            process.pid,
            databaseShipIds.get(process.ship_id),
            process.priority,
            process.arrival,
            process.burst,
            process.berths,
            process.cranes,
            process.trucks,
        ]);
        await connection.query(
            `INSERT INTO ship_requests
                (simulation_id, pid, ship_id, priority, arrival, burst, berth_count, crane_count, truck_count)
             VALUES ${requestRows.map(() => "(?, ?, ?, ?, ?, ?, ?, ?, ?)").join(", ")}`,
            requestRows.flat()
        );

        await connection.commit();
        transactionStarted = false;
        res.status(201).json({ id: simulationId, name });
    } catch (error) {
        if (connection && transactionStarted) {
            try {
                await connection.rollback();
            } catch (rollbackError) {
                console.error("Could not roll back saved simulation:", rollbackError.message);
            }
        }
        console.error("Could not save simulation:", error.message);
        res.status(500).json({ error: "Could not save simulation" });
    } finally {
        if (connection) connection.release();
    }
});

// Foreign-key cascades remove the simulation's ships, resources, and requests.
app.delete("/api/simulations/:id", async (req, res) => {
    const simulationId = Number(req.params.id);
    if (!Number.isSafeInteger(simulationId) || simulationId < 1) {
        return res.status(400).json({ error: "Invalid simulation ID" });
    }

    try {
        const [result] = await promiseDb.execute(
            "DELETE FROM simulations WHERE simulation_id = ?",
            [simulationId]
        );
        if (result.affectedRows === 0) {
            return res.status(404).json({ error: "Saved simulation not found" });
        }
        res.status(204).end();
    } catch (error) {
        console.error("Could not delete saved simulation:", error.message);
        res.status(500).json({ error: "Could not delete saved simulation" });
    }
});

// Crane MLP prediction endpoint. The Python service currently runs in
// SYNTHETIC_DEMO_ONLY mode until a real, labelled crane dataset is supplied.
app.post("/api/crane-prediction", async (req, res) => {
    const craneId = typeof req.body?.crane_id === "string" ? req.body.crane_id.trim() : "";
    const { temperature, vibration, load_percent, operating_hours } = req.body ?? {};
    const readings = [temperature, vibration, load_percent, operating_hours];

    if (!craneId || craneId.length > 80 || readings.some((value) => typeof value !== "number" || !Number.isFinite(value))) {
        return res.status(400).json({ error: "Provide a crane ID and numeric temperature, vibration, load_percent, and operating_hours values." });
    }
    if (temperature < -20 || temperature > 200 || vibration < 0 || vibration > 30
        || load_percent < 0 || load_percent > 150 || operating_hours < 0 || operating_hours > 500000) {
        return res.status(400).json({ error: "One or more crane readings are outside the accepted input range." });
    }

    try {
        const aiResponse = await fetch("http://127.0.0.1:8000/predict", {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({ temperature, vibration, load_percent, operating_hours }),
            signal: AbortSignal.timeout(10000),
        });
        const prediction = await aiResponse.json().catch(() => ({}));
        if (!aiResponse.ok) {
            return res.status(502).json({ error: prediction.detail || "The Python MLP service could not produce a prediction." });
        }

        const [insertResult] = await promiseDb.execute(
            `INSERT INTO crane_ai_predictions
                (crane_id, temperature, vibration, load_percent, operating_hours,
                 failure_probability, risk_category, model_version, model_mode)
             VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)`,
            [craneId, temperature, vibration, load_percent, operating_hours,
                prediction.failure_probability, prediction.risk_category,
                prediction.model_version, prediction.mode]
        );

        return res.status(201).json({
            prediction_id: insertResult.insertId,
            crane_id: craneId,
            ...prediction,
            saved: true,
        });
    } catch (error) {
        console.error("Crane prediction failed:", error.message);
        if (error.code === "ER_NO_SUCH_TABLE") {
            return res.status(500).json({ error: "Missing crane_ai_predictions table. Run database_connectivity/migration_crane_ai.sql first." });
        }
        return res.status(503).json({ error: "Crane AI service or database is unavailable. Check the Python service and MySQL connection." });
    }
});

app.get("/api/crane-prediction/:craneId", async (req, res) => {
    const craneId = String(req.params.craneId || "").trim();
    if (!craneId || craneId.length > 80) return res.status(400).json({ error: "Invalid crane ID." });
    try {
        const [rows] = await promiseDb.execute(
            `SELECT prediction_id, crane_id, temperature, vibration, load_percent,
                    operating_hours, failure_probability, risk_category, model_version,
                    model_mode, created_at
             FROM crane_ai_predictions WHERE crane_id = ?
             ORDER BY created_at DESC, prediction_id DESC LIMIT 20`,
            [craneId]
        );
        res.json(rows);
    } catch (error) {
        console.error("Could not load crane prediction history:", error.message);
        res.status(500).json({ error: "Could not load crane prediction history." });
    }
});

