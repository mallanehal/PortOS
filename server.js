const express = require("express");
const fs = require("fs");
const path = require("path");
const { spawnSync } = require("child_process");
const db = require("./dbms");
// Promise-based queries are used by the async save/load endpoints below.
const promiseDb = db.promise();

const app = express();
app.use(express.json({ limit: "1mb" }));

// Paths for the existing C++ simulator and the files it reads and writes.
const cppDirectory = path.resolve(__dirname, "../Backend/OS_Logic");
const executablePath = path.join(cppDirectory, "a.exe");
const inputPath = path.join(cppDirectory, "input.txt");
const outputPath = path.join(cppDirectory, "output.txt");

// Keep user text from breaking the pipe-delimited C++ input format.
function escapeInput(text) {
    return String(text ?? "").replace(/[\r\n|]/g, " ");
}

// Run a simulation directly through the C++ backend; this route does not save it to MySQL.
app.post("/api/simulate", (req, res) => {
    try {
        const config = req.body;
        const ships = config.ships ?? [];
        const processes = config.processes ?? [];
        const berthCount = (config.berths ?? []).length;
        const craneCount = (config.cranes ?? []).length;
        const truckCount = (config.trucks ?? []).length;

        if (!processes.length) {
            return res.status(400).json({ error: "At least one process is required" });
        }
        if (!ships.length) {
            return res.status(400).json({ error: "At least one ship is required" });
        }
        if (!berthCount) {
            return res.status(400).json({ error: "The port needs at least one berth" });
        }

        const shipIds = new Set(ships.map((ship) => Number(ship.ship_id)));
        for (const process of processes) {
            const shipId = Number(process.ship_id);
            const burst = Number(process.burst ?? 3);
            const arrival = Number(process.arrival);
            const priority = Number(process.priority);
            const berth = Number(process.berthneeded ?? 0);
            const crane = Number(process.craneneeded ?? 0);
            const truck = Number(process.truckneeded ?? 0);

            if (!shipIds.has(shipId)) return res.status(400).json({ error: `P${process.pid} references an unknown ship ID ${shipId}` });
            if (![burst, arrival, priority, berth, crane, truck].every(Number.isFinite) || burst < 1 || arrival < 0 || priority < 1 || berth < 0 || crane < 0 || truck < 0) {
                return res.status(400).json({ error: `P${process.pid} has an invalid burst, arrival, priority, or resource quantity` });
            }
            if (berth > berthCount || crane > craneCount || truck > truckCount) {
                return res.status(400).json({ error: `P${process.pid} requests more resources than the port owns` });
            }
        }

        const lines = ["# Generated by PortOS frontend"];
        for (const ship of ships) {
            lines.push(`SHIP ${ship.ship_id}|${escapeInput(ship.name)}|${escapeInput(ship.type)}|${escapeInput(ship.country)}|${escapeInput(ship.captain_name)}`);
        }

        (config.berths ?? []).forEach((berth, index) => {
            lines.push(`BERTH ${101 + index} ${berth.size}`);
        });
        (config.cranes ?? []).forEach((crane, index) => {
            lines.push(`CRANE ${201 + index} ${crane.size}`);
        });
        (config.trucks ?? []).forEach((truck, index) => {
            lines.push(`TRUCK ${301 + index} ${truck.size}`);
        });

        lines.push(`# berths=${berthCount} cranes=${craneCount} trucks=${truckCount}`);
        processes.forEach((process) => {
            const burst = Number(process.burst ?? 3);
            lines.push(`PROCESS ${process.pid} ${process.ship_id} ${process.priority} ${process.arrival} ${burst} ${process.berthneeded ?? 0} ${process.craneneeded ?? 0} ${process.truckneeded ?? 0}`);
        });

        fs.writeFileSync(inputPath, lines.join("\n") + "\n", "utf8");

        const cpp = spawnSync(executablePath, [], { cwd: cppDirectory, encoding: "utf8", maxBuffer: 20 * 1024 * 1024 });
        if (cpp.error) {
            return res.status(500).json({ error: `Could not run a.exe: ${cpp.error.message}` });
        }
        if (cpp.status !== 0) {
            return res.status(500).json({ error: "C++ simulation failed", stdout: cpp.stdout, stderr: cpp.stderr });
        }
        if (!fs.existsSync(outputPath)) {
            return res.status(500).json({ error: "C++ simulation did not create output.txt" });
        }

        const result = JSON.parse(fs.readFileSync(outputPath, "utf8"));
        result.consoleOutput = cpp.stdout;
        result.input = { ships, berths: config.berths ?? [], cranes: config.cranes ?? [], trucks: config.trucks ?? [], processes };
        res.json(result);
    } catch (error) {
        res.status(500).json({ error: error.message });
    }
});

