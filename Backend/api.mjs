import { execFile as execFileCallback } from "node:child_process";
import { rmSync } from "node:fs";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const execFile = promisify(execFileCallback);
const backendDirectory = path.dirname(fileURLToPath(import.meta.url));
const sourcePath = path.join(backendDirectory, "OS_Logic", "main.cpp");
const resourceTypes = [
  { key: "berths", row: "BERTH", label: "berths" },
  { key: "cranes", row: "CRANE", label: "cranes" },
  { key: "trucks", row: "TRUCK", label: "trucks" },
];
let executablePath;
let buildPromise;

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

function isInteger(value, minimum = 0) {
  return Number.isInteger(value) && value >= minimum;
}

function validateText(value, label) {
  assert(typeof value === "string" && value.trim(), `${label} is required.`);
  assert(!/[|\r\n]/.test(value), `${label} cannot contain | or a line break.`);
  return value.trim();
}

function validateConfig(config) {
  assert(config && typeof config === "object", "A simulation configuration is required.");
  const resourceIds = {};
  for (const resource of resourceTypes) {
    const items = config[resource.key];
    assert(Array.isArray(items) && items.length > 0, `Add at least one ${resource.label.slice(0, -1)}.`);
    const ids = new Set();
    items.forEach((item) => {
      assert(item && isInteger(item.num, 1), `Each ${resource.label.slice(0, -1)} needs a positive ID.`);
      assert(!ids.has(item.num), `${resource.label} IDs must be unique.`);
      ids.add(item.num);
      assert(["Small", "Medium", "Large"].includes(item.size), `Invalid ${resource.label.slice(0, -1)} size.`);
    });
    resourceIds[resource.key] = ids;
  }

  assert(Array.isArray(config.ships) && config.ships.length > 0, "Register at least one ship.");
  const shipIds = new Set();
  for (const ship of config.ships) {
    assert(ship && isInteger(ship.ship_id, 1), "Each ship needs a positive ID.");
    assert(!shipIds.has(ship.ship_id), "Ship IDs must be unique.");
    shipIds.add(ship.ship_id);
    for (const key of ["name", "type", "country", "captain_name"]) {
      if (key === "country" || key === "captain_name") {
        const value = ship[key] ?? "";
        assert(typeof value === "string" && !/[|\r\n]/.test(value), `Ship ${key} cannot contain | or a line break.`);
      } else {
        validateText(ship[key], `Ship ${key}`);
      }
    }
  }

  assert(Array.isArray(config.processes) && config.processes.length > 0, "Add at least one ship request.");
  const processIds = new Set();
  for (const process of config.processes) {
    assert(process && isInteger(process.pid, 1), "Each process needs a positive ID.");
    assert(!processIds.has(process.pid), "Process IDs must be unique.");
    processIds.add(process.pid);
    assert(shipIds.has(process.ship_id), `P${process.pid} refers to an unknown ship.`);
    assert(isInteger(process.priority, 1), `P${process.pid} priority must be at least 1.`);
    assert(isInteger(process.arrival), `P${process.pid} arrival time must be zero or greater.`);
    assert(isInteger(process.burst, 1), `P${process.pid} burst must be at least 1.`);
    let hasRequest = false;
    for (const key of ["berths", "cranes", "trucks"]) {
      const count = process[key];
      assert(isInteger(count), `P${process.pid} ${key} request must be zero or greater.`);
      assert(count <= resourceIds[key].size, `P${process.pid} requests more ${key} than the port has.`);
      hasRequest ||= count > 0;
    }
    assert(hasRequest, `P${process.pid} must request at least one resource.`);
  }
}

function makeInput(config) {
  const lines = ["# Generated by PortOS frontend"];
  for (const ship of config.ships) {
    lines.push(`SHIP ${ship.ship_id}|${ship.name.trim()}|${ship.type.trim()}|${(ship.country ?? "").trim()}|${(ship.captain_name ?? "").trim()}`);
  }
  for (const resource of resourceTypes) {
    for (const item of config[resource.key]) {
      lines.push(`${resource.row} ${item.num} ${item.size}`);
    }
  }
  for (const process of config.processes) {
    lines.push(`PROCESS ${process.pid} ${process.ship_id} ${process.priority} ${process.arrival} ${process.burst} ${process.berths} ${process.cranes} ${process.trucks}`);
  }
  return `${lines.join("\n")}\n`;
}

async function getExecutable() {
  if (executablePath) return executablePath;
  if (!buildPromise) {
    buildPromise = (async () => {
      const buildDirectory = await mkdtemp(path.join(os.tmpdir(), "portos-build-"));
      const executable = path.join(buildDirectory, process.platform === "win32" ? "portos.exe" : "portos");
      try {
        await execFile("g++", ["-std=c++17", sourcePath, "-o", executable], { timeout: 60000 });
      } catch (error) {
        await rm(buildDirectory, { recursive: true, force: true });
        const detail = error.stderr?.trim() || error.message;
        throw new Error(`Could not compile the C++ backend. Install g++ and ensure it is on PATH. ${detail}`);
      }
      process.once("exit", () => rmSync(buildDirectory, { recursive: true, force: true }));
      executablePath = executable;
      return executable;
    })();
  }
  return buildPromise;
}

async function runSimulation(config) {
  validateConfig(config);
  const executable = await getExecutable();
  const runDirectory = await mkdtemp(path.join(os.tmpdir(), "portos-run-"));
  try {
    await writeFile(path.join(runDirectory, "input.txt"), makeInput(config), "utf8");
    try {
      await execFile(executable, [], { cwd: runDirectory, timeout: 30000, maxBuffer: 20 * 1024 * 1024 });
    } catch (error) {
      const detail = error.stderr?.trim() || error.stdout?.trim() || error.message;
      throw new Error(`The C++ simulation failed. ${detail}`);
    }
    const output = await readFile(path.join(runDirectory, "output.txt"), "utf8");
    const result = JSON.parse(output);
    assert(Array.isArray(result.timeline) && Array.isArray(result.bankerEvents), "The C++ backend returned an incomplete result.");
    return result;
  } finally {
    await rm(runDirectory, { recursive: true, force: true });
  }
}

async function readJson(request) {
  const chunks = [];
  let length = 0;
  for await (const chunk of request) {
    length += chunk.length;
    if (length > 1024 * 1024) throw new Error("Request body exceeds the 1 MB limit.");
    chunks.push(chunk);
  }
  try {
    return JSON.parse(Buffer.concat(chunks).toString("utf8"));
  } catch {
    throw new Error("Request body must be valid JSON.");
  }
}

function sendJson(response, status, value) {
  response.statusCode = status;
  response.setHeader("Content-Type", "application/json; charset=utf-8");
  response.end(JSON.stringify(value));
}

function handler(request, response) {
  if (request.method !== "POST") {
    sendJson(response, 405, { error: "Use POST to run a simulation." });
    return;
  }
  readJson(request)
    .then((config) => runSimulation(config))
    .then((result) => sendJson(response, 200, result))
    .catch((error) => sendJson(response, error.message.includes("limit") ? 413 : 400, { error: error.message }));
}

export default function portOsApi() {
  return {
    name: "port-os-cpp-api",
    configureServer(server) {
      server.middlewares.use("/api/simulate", handler);
    },
    configurePreviewServer(server) {
      server.middlewares.use("/api/simulate", handler);
    },
  };
}
